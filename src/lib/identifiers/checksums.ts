/** Identifier maths — the only part of product checking that is *proof*. */

export function luhnValid(digits: string): boolean {
  const clean = digits.replace(/\D/g, "");
  if (clean.length < 2) return false;
  let sum = 0;
  let alt = false;
  for (let i = clean.length - 1; i >= 0; i -= 1) {
    let n = Number.parseInt(clean[i], 10);
    if (alt) {
      n *= 2;
      if (n > 9) n -= 9;
    }
    sum += n;
    alt = !alt;
  }
  return sum % 10 === 0;
}

export interface ImeiResult {
  found: boolean;
  value?: string;
  checksumValid?: boolean;
  tac?: string;
  detail?: string;
}

export function inspectImei(input: string): ImeiResult {
  const match = input.replace(/[\s-]/g, "").match(/(?:^|\D)(\d{15})(?:\D|$)/);
  if (!match) return { found: false };
  const value = match[1];
  const valid = luhnValid(value);
  return {
    found: true,
    value,
    checksumValid: valid,
    tac: value.slice(0, 8),
    detail: valid
      ? "Luhn checksum passes and the TAC (first 8 digits) is well formed. This proves the *number* is structurally valid — not that the handset is genuine."
      : "Luhn checksum fails. A real IMEI always satisfies the check digit, so this string was not issued as an IMEI (or was mistyped).",
  };
}

export interface BarcodeResult {
  found: boolean;
  value?: string;
  format?: "EAN-13" | "UPC-A" | "EAN-8" | "GTIN-14" | "ISBN-13";
  checksumValid?: boolean;
  gs1Prefix?: string;
  prefixMeaning?: string;
  detail?: string;
}

const GS1_PREFIX_NOTES: Array<[RegExp, string]> = [
  [/^97[89]/, "Bookland (ISBN-13) prefix — assigned to publishers, not electronics"],
  [/^0[0-9]/, "GS1 US / Canada numbering block"],
  [/^4[5-9]/, "GS1 Japan numbering block"],
  [/^69[0-5]/, "GS1 China numbering block"],
  [/^88[0-9]/, "GS1 Korea numbering block"],
  [/^4[0-4]/, "GS1 Germany numbering block"],
  [/^50/, "GS1 United Kingdom numbering block"],
  [/^8[0-9]/, "GS1 Italy / Spain / Netherlands region"],
  [/^0?0?00/, "Unassigned or restricted GS1 range — treat with caution"],
];

export function gtinCheckDigitValid(digits: string): boolean {
  const clean = digits.replace(/\D/g, "");
  if (![8, 12, 13, 14].includes(clean.length)) return false;
  let sum = 0;
  const body = clean.slice(0, -1);
  const check = Number.parseInt(clean.slice(-1), 10);
  for (let i = 0; i < body.length; i += 1) {
    const n = Number.parseInt(body[i], 10);
    const fromRight = body.length - i;
    sum += n * (fromRight % 2 === 1 ? 3 : 1);
  }
  const expected = (10 - (sum % 10)) % 10;
  return expected === check;
}

export function inspectBarcode(input: string): BarcodeResult {
  const clean = input.replace(/[\s-]/g, "");
  const match = clean.match(/(?:^|\D)(\d{8}|\d{12}|\d{13}|\d{14})(?:\D|$)/);
  const isbn = input.toUpperCase().match(/ISBN[-:\s]*(\d{13})/);
  const raw = isbn?.[1] ?? match?.[1];
  if (!raw) return { found: false };

  const len = raw.length;
  const format: BarcodeResult["format"] =
    len === 13 ? (raw.startsWith("978") || raw.startsWith("979") ? "ISBN-13" : "EAN-13")
    : len === 12 ? "UPC-A"
    : len === 8 ? "EAN-8"
    : "GTIN-14";

  const valid = gtinCheckDigitValid(raw);
  const prefix = raw.slice(0, 3);
  const prefixMeaning = GS1_PREFIX_NOTES.find(([re]) => re.test(raw))?.[1];

  return {
    found: true,
    value: raw,
    format,
    checksumValid: valid,
    gs1Prefix: prefix,
    prefixMeaning,
    detail: valid
      ? `The ${format} check digit is correct and the GS1 prefix ${prefix} is inside an allocated numbering block. Counterfeiters routinely copy valid barcodes from genuine packaging, so a passing check digit is necessary but never sufficient.`
      : `The ${format} check digit is incorrect — this code was mistyped, invented, or generated by a tool that ignored the GS1 modulo-10 algorithm. Genuine retail packaging does not carry invalid check digits.`,
  };
}

const HOMOGLYPHS: Record<string, string> = {
  "0": "o", "1": "l", "3": "e", "4": "a", "5": "s", "7": "t", "8": "b", "9": "g",
  "ı": "i", "ì": "i", "í": "i", "î": "i", "ï": "i",
  "а": "a", "е": "e", "о": "o", "р": "p", "с": "c", "у": "y", "х": "x",
  "ѕ": "s", "ԁ": "d", "ԛ": "q", "ԝ": "w",
  "‑": "-", "‐": "-", "—": "-", "–": "-",
};

export function foldHomoglyphs(input: string): string {
  return input
    .normalize("NFKC")
    .toLowerCase()
    .split("")
    .map((c) => HOMOGLYPHS[c] ?? c)
    .join("");
}

export function levenshtein(a: string, b: string): number {
  if (a === b) return 0;
  if (!a.length) return b.length;
  if (!b.length) return a.length;
  let prev = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i += 1) {
    const row = [i];
    for (let j = 1; j <= b.length; j += 1) {
      row[j] = Math.min(
        prev[j] + 1,
        row[j - 1] + 1,
        prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1),
      );
    }
    prev = row;
  }
  return prev[b.length];
}

/** Normalises messy model strings so catalogue matching is order/spacing tolerant. */
export function normalizeModel(input: string): string {
  return input
    .toUpperCase()
    .replace(/\(([^)]*)\)/g, " $1 ")
    .replace(/[^A-Z0-9]+/g, "")
    .slice(0, 40);
}

export function modelTokens(input: string): string[] {
  const norm = normalizeModel(input);
  const tokens = new Set<string>();
  tokens.add(norm);
  // sliding windows catch "SM-S928B/DS" vs "SM S928B"
  for (let len = 4; len <= 12; len += 1) {
    for (let i = 0; i + len <= norm.length; i += 1) tokens.add(norm.slice(i, i + len));
  }
  return [...tokens];
}

export function looksLikeModelNumber(input: string): boolean {
  const t = input.trim();
  if (t.length < 4 || t.length > 32) return false;
  if (!/[A-Za-z]/.test(t) || !/\d/.test(t)) return false;
  return /^(?:[A-Z]{1,5}[-\s]?)?[A-Z0-9][A-Z0-9/.\-\s]{2,28}[A-Z0-9]$/i.test(t);
}

/** A number followed by a short unit or suffix ("256GB", "5000mAh", "45W", "1990s") — a quantity, not a model code. */
const QUANTITY_RE = /^\d+(?:\.\d+)?[a-z]{0,4}$/i;

/** Tokens inside free text that have the shape of a manufacturer model code ("SM-S928B/DS", "A2147"). */
export function modelCodesInText(text: string): string[] {
  return text
    .split(/[\s,;|]+/)
    .map((t) => t.replace(/^[("'[]+|[)"'\].,:;!?]+$/g, ""))
    .filter((t) => t.length >= 4 && t.length <= 24 && looksLikeModelNumber(t) && !QUANTITY_RE.test(t));
}
