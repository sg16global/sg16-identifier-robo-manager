// Embeds private/legal/nm-certificate-of-organization.webp into the server bundle as
// src/lib/legal/certificate-image.ts, so /api/legal/certificate needs no file system
// (Cloudflare Workers have none) and the image never gets a static URL.
// Run after replacing the certificate: npm run embed:certificate
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "private", "legal", "nm-certificate-of-organization.webp");
const target = join(root, "src", "lib", "legal", "certificate-image.ts");

const bytes = readFileSync(source);
if (bytes.subarray(0, 4).toString("ascii") !== "RIFF" || bytes.subarray(8, 12).toString("ascii") !== "WEBP") {
  throw new Error(`${source} is not a WebP image`);
}
const base64 = bytes.toString("base64");
const lines = base64.match(/.{1,120}/g).map((line) => `  "${line}"`).join(",\n");

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// GENERATED by scripts/embed-certificate.mjs from private/legal/nm-certificate-of-organization.webp.
// Do not edit by hand; re-run \`npm run embed:certificate\` after replacing the certificate.
// Server-only: imported by app/api/legal/certificate/route.ts, never by client code.

export const CERTIFICATE_MIME = "image/webp";

/** The certificate's ${bytes.length} bytes, base64-encoded. */
export const CERTIFICATE_BASE64 = [
${lines},
].join("");
`,
);
console.log(`Embedded ${bytes.length} bytes into ${target}`);
